export function messages(lang) {
  return MESSAGES[lang] ?? MESSAGES.en
}

// "{planned} → {used}" with { planned: '1.2k', used: '310' }
export function fill(template, values) {
  return template.replace(/\{(\w+)\}/g, (whole, key) => (key in values ? String(values[key]) : whole))
}

// A category name from /context, in the session's language when known
export function categoryName(lang, name) {
  return messages(lang).categories[name] ?? name
}

// Language names as people write them in Claude Code's `language` setting,
// in English, in the language itself, and in French
const NAMES = {
  en: ['english', 'anglais', 'inglés', 'ingles', 'inglês'],
  zh: ['chinese', 'mandarin', 'mandarin chinese', 'simplified chinese', '中文', '简体中文', '汉语', '普通话', 'chinois'],
  hi: ['hindi', 'हिन्दी', 'हिंदी'],
  es: ['spanish', 'español', 'espanol', 'castellano', 'espagnol'],
  ar: ['arabic', 'العربية', 'عربي', 'arabe', 'árabe'],
  fr: ['french', 'français', 'francais', 'francés', 'francês'],
  bn: ['bengali', 'bangla', 'বাংলা'],
  pt: ['portuguese', 'português', 'portugues', 'portugais', 'portugués'],
}

// 'fr', 'fr_FR.UTF-8', 'zh-Hans-CN', 'Spanish', 'العربية' -> a supported
// code, or null (C, POSIX, empty, or a language this mod has no text for)
export function languageOf(value) {
  if (typeof value !== 'string') return null
  const text = value.trim().toLowerCase()
  if (!text) return null
  for (const [code, names] of Object.entries(NAMES)) {
    if (names.includes(text)) return code
  }
  const code = text.split(/[_.@-]/)[0]
  return LANGUAGES.includes(code) ? code : null
}

// The first source that names a supported language wins:
// RTK_GAIN_LANG, Claude Code's `language` setting, the locale, the system's.
export function detectLanguage({ explicit, setting, lcAll, lcMessages, lang, system } = {}) {
  for (const value of [explicit, setting, lcAll, lcMessages, lang, system]) {
    const code = languageOf(value)
    if (code) return code
  }
  return 'en'
}
